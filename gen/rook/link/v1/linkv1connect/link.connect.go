// The device–host link protocol: the channel through which a paired
// remote surface (a phone) watches a host's live projection and sends
// back the small vocabulary of actions the host accepts.
//
// Design stances this file encodes, per
// docs/adr/0001-cloud-coordinates-ide-decides.md and
// docs/adr/0003-qr-pairing-pinned-tls.md:
//
//   - Transport is not identity, and reachability is not authorization.
//     Bonjour finds hosts; the QR-pinned TLS key plus the Ed25519
//     pairing handshake prove which host this is; a per-connection
//     signed challenge proves which device this is; and a capability
//     check guards every RPC after that. Four separate questions, four
//     separate mechanisms.
//   - The link is a latency rail, never a correctness rail. Everything
//     it carries is either a snapshot (latest wins, no history) or an
//     idempotent instruction keyed by the same natural ID the cloud
//     rail uses — a command that arrives over both rails is one
//     command, deduped by the host's delivery journal.
//   - Every action is TYPED and allowlisted. There is deliberately no
//     ExecuteShell or RunPrompt here and one must never be added; the
//     command vocabulary grows by protocol change with review, not by
//     a client sending a new string.
//   - Sessions outlive connections. A session token names an
//     authenticated device, not a socket; reconnecting resumes logical
//     state, and revocation kills the device's access mid-stream.

